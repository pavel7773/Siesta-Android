private val promoMinimum = Regex("Промокод доступен от ([0-9]+) ₽")

fun Resources.uiMessage(message: String): String {
    messageResources[message]?.let { return getString(it) }
    promoMinimum.matchEntire(message)?.let {
        return getString(R.string.ui_this_promo_code_requires_an_order_of_at_least_10, it.groupValues[1])
    }
    return message
}
